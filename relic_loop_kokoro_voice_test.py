"""Generate standalone Kokoro narrator samples for Relic Loop voice audition."""
from __future__ import annotations

from pathlib import Path
import soundfile as sf
from kokoro import KPipeline

SAMPLE_TEXT = (
    "He was five seconds late, so he made the worst decision of his morning. "
    "He skipped breakfast, refused to tie his shoe, and sprinted for the bus. "
    "He actually caught it — then realized it was going in the opposite direction. "
    "Instead of getting off, he decided to stay on because he was already embarrassed. "
    "Twenty minutes later, the driver stopped at the airport. "
    "He stared out the window, looked at his untied shoe, and finally admitted one thing: "
    "saving five seconds had somehow cost him an entire morning."
)

# Male American-English voices. We are auditioning several character styles,
# not changing the Relic Loop pipeline yet.
VOICES = {
    "am_echo": "am_echo",
    "am_puck": "am_puck",
    "am_michael": "am_michael",
}

OUT = Path("voice_samples_kokoro")
OUT.mkdir(parents=True, exist_ok=True)


def synthesize(name: str, voice: str, pipeline: KPipeline) -> None:
    target = OUT / f"kokoro_{name}.wav"
    print(f"[KOKORO VOICE TEST] {voice} -> {target}")

    chunks = []
    for _, _, audio in pipeline(SAMPLE_TEXT, voice=voice):
        chunks.append(audio)

    if not chunks:
        raise RuntimeError(f"Kokoro produced no audio for {voice}")

    import numpy as np

    audio = np.concatenate(chunks)
    sf.write(target, audio, 24000)

    if not target.exists() or target.stat().st_size < 1000:
        raise RuntimeError(f"No usable audio produced for {voice}")


def main() -> None:
    # 'a' = American English.
    pipeline = KPipeline(lang_code="a")

    for name, voice in VOICES.items():
        synthesize(name, voice, pipeline)

    (OUT / "README.txt").write_text(
        "Relic Loop Kokoro voice audition\n\n"
        "All samples use the exact same Relic Loop narration.\n"
        "These are standalone Kokoro samples only; the production pipeline has not been changed.\n"
        "Voices: am_echo, am_puck, am_michael.\n"
        "Audio is 24 kHz WAV generated by Kokoro.\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
